#!/usr/bin/env python3
"""Give each REL module its own symbol namespace in the host link.

On the console every REL is linked separately, so several modules can define RELMain/RELExit,
module-local Load* functions and weak template copies under the same names. A flat host link
cannot hold them. This tool is run by CMake (see mp_scope_modules in CMakeLists.txt) in two modes.

  registry  Read the module list (one line per module: "Name;obj;obj;...") and write the
            compiled-module registry include (name, prolog, epilog per module that defines
            RELMain/RELExit), which platform/compiled_modules.cpp includes.
  scope     For every module: partially link its objects (ld -r) into <outdir>/<Name>.o, rename
            RELMain/RELExit to mp_rel_<Name>_prolog/_epilog, and localize every other defined
            global/weak symbol except those that an object outside the module references and
            that nothing outside the module defines.
  scope --format macho
            macOS/iOS: the same per-object rename as coff, on Mach-O objects. Names keep their
            leading underscore (_sym -> _mp_rel_<Name>__sym, _RELMain -> _mp_rel_<Name>_prolog),
            so the C symbol mp_rel_<Name>_prolog resolves. No .drectve section exists.
  scope --format coff
            Windows (lld-link has no -r link). Each module object gets its own scoped copy,
            --outputs lists "Name;out;out..." (one output per input object, same order). Every
            module-private symbol (the same set the ELF mode localizes) is renamed with
            llvm-objcopy --redefine-syms to mp_rel_<Name>__<symbol> in all of the module's objects, so
            references inside the module still resolve, COMDAT leaders (inline functions,
            templates) become per-module, and RELMain/RELExit become mp_rel_<Name>_prolog/_epilog.
            Static initializers live in sections (.CRT$XC*) and need no renaming.

    scope_module.py registry --modules LIST --out INC
    scope_module.py scope --modules LIST --others LIST --outdir DIR --ld LD --objcopy OBJCOPY --nm NM
    scope_module.py scope --format coff --modules LIST --others LIST --outputs LIST --outdir DIR \
                          --objcopy OBJCOPY --nm NM
"""
import argparse
import os
import re
import subprocess
import sys

# The leading-underscore forms are Mach-O's (every C symbol carries one).
ENTRY = {"prolog": re.compile(r"^(_Z7RELMainv|RELMain|\?RELMain@@YAXXZ|__Z7RELMainv|_RELMain)$"),
         "epilog": re.compile(r"^(_Z7RELExitv|RELExit|\?RELExit@@YAXXZ|__Z7RELExitv|_RELExit)$")}
# COFF symbols the linker or CRT resolve by name; never rename them if a module defines one.
COFF_RESERVED = {"_tls_used", "_fltused", "__ImageBase", "_tls_index", "mainCRTStartup", "WinMainCRTStartup",
                 "main", "wmain", "WinMain", "DllMain"}
# Mach-O symbols dyld or the linker resolve by name. Local labels (ltmp*, l_*, L*) are not
# external, so nm -g never lists them and they are never renamed.
MACHO_RESERVED = {"_main", "__mh_execute_header", "__mh_bundle_header", "__mh_dylib_header",
                  "___dso_handle"}


def read_modules(path):
    mods = []
    for line in open(path).read().splitlines():
        if line.strip():
            name, *objs = line.split(";")
            mods.append((name, [o for o in objs if o]))
    return mods


def nm(tool, objs, *flags):
    """Return {symbol: type} lists from nm -P over objs, in chunks to bound the command line."""
    out = []
    # At most 200 objects and about 24000 characters a run: a Windows command line holds 32767,
    # which 200 of a deep build folder's object paths (an Android build from Windows) overran.
    chunks, chunk, length = [], [], 0
    for obj in objs:
        if chunk and (len(chunk) >= 200 or length + len(obj) + 3 > 24000):
            chunks.append(chunk)
            chunk, length = [], 0
        chunk.append(obj)
        length += len(obj) + 3
    if chunk:
        chunks.append(chunk)
    for chunk in chunks:
        r = subprocess.run([tool, "--no-demangle", "-P", *flags, *chunk],
                           capture_output=True, text=True, check=True)
        for line in r.stdout.splitlines():
            parts = line.split()
            # "name type [value size]"; per-file header lines end in ':' and have one field.
            if len(parts) >= 2:
                out.append((parts[0], parts[1]))
    return out


def entry_points(nm_tool, objs):
    found = {}
    for sym, typ in nm(nm_tool, objs, "--defined-only", "-g"):
        for kind, rx in ENTRY.items():
            if typ in "TtWw" and rx.match(sym):
                found[kind] = sym
    return found


def registry(args):
    lines = ["// GENERATED by tools/scope_module.py - do not edit.\n"]
    decls, rows = [], []
    for name, objs in read_modules(args.modules):
        eps = entry_points(args.nm, objs)
        if "prolog" not in eps:
            continue
        decls.append(f"void mp_rel_{name}_prolog();")
        epilog = "nullptr"
        if "epilog" in eps:
            decls.append(f"void mp_rel_{name}_epilog();")
            epilog = f"&mp_rel_{name}_epilog"
        # A module whose only source is the shared entry-point stub has no host body: its
        # actors never appear, and the registry is the one place that knows its name, so the
        # prolog can say which module an area asked for and found empty.
        stub = any("PortModuleStubs.cpp" in o for o in objs)
        rows.append(f'    {{"{name}", "{name}", &mp_rel_{name}_prolog, {epilog}, '
                    f'{"true" if stub else "false"}}},')
    lines.append('#ifdef MP_MODULE_DECLS\nextern "C" {\n' + "\n".join(decls) + "\n}\n#else")
    lines.append("constexpr CompiledModule kCompiledModules[] = {\n" + "\n".join(rows) + "\n};\n#endif\n")
    new = "\n".join(lines)
    if not os.path.exists(args.out) or open(args.out).read() != new:
        os.makedirs(os.path.dirname(args.out), exist_ok=True)
        open(args.out, "w").write(new)


def scope(args):
    mods = read_modules(args.modules)
    others = [l for l in open(args.others).read().splitlines() if l.strip()]
    all_module_objs = {o for _, objs in mods for o in objs}
    others = [o for o in others if o not in all_module_objs]

    defined_outside = {s for s, t in nm(args.nm, others, "--defined-only", "-g") if t not in "Uu"}
    undef_outside = {s for s, t in nm(args.nm, others, "-u") if t == "U"}
    os.makedirs(args.outdir, exist_ok=True)

    # Pass 1: partial links, so every module's own undefined references are known.
    partials = {}
    for name, objs in mods:
        partials[name] = os.path.join(args.outdir, f"{name}.raw.o")
        # --force-group-allocation dissolves COMDAT groups: their signature symbols are localized
        # below, but ld still folds groups by signature name, so a module's inline functions
        # (and DW.ref.__gxx_personality_v0) were discarded in favour of another object's group
        # while the module's own references stayed bound to the localized, now-empty copy.
        subprocess.run([args.ld, "-r", "--force-group-allocation", "-o", partials[name], *objs],
                       check=True)
    undef_of = {name: {s for s, t in nm(args.nm, [partials[name]], "-u") if t == "U"}
                for name, _ in mods}

    for name, _ in mods:
        partial, final = partials[name], os.path.join(args.outdir, f"{name}.o")
        eps = entry_points(args.nm, [partial])
        redefine = []
        if "prolog" in eps:
            redefine += ["--redefine-sym", f"{eps['prolog']}=mp_rel_{name}_prolog"]
        if "epilog" in eps:
            redefine += ["--redefine-sym", f"{eps['epilog']}=mp_rel_{name}_epilog"]

        # Another module's references count too: a symbol this module defines and a sibling needs,
        # with no definition outside any module, stays global.
        needed = set(undef_outside)
        for other, syms in undef_of.items():
            if other != name:
                needed |= syms
        entry_names = set(eps.values())
        local = sorted(s for s, t in nm(args.nm, [partial], "--defined-only", "-g")
                       if t not in "Uu" and s not in entry_names
                       and not (s in needed and s not in defined_outside))
        symfile = os.path.join(args.outdir, f"{name}.localize")
        open(symfile, "w").write("".join(f"{s}\n" for s in local))

        stage = os.path.join(args.outdir, f"{name}.renamed.o")
        subprocess.run([args.objcopy, *redefine, partial, stage], check=True)
        if local:
            subprocess.run([args.objcopy, f"--localize-symbols={symfile}", stage, final], check=True)
        else:
            # A module whose only globals are its own entry points (the shared entry-point stub
            # in tools/modules_port.txt, for instance) has nothing to localize, and objcopy
            # rejects an empty symbol list.
            subprocess.run([args.objcopy, stage, final], check=True)
        os.remove(stage)


def scope_coff(args):
    scope_rename(args, "coff")


def scope_macho(args):
    scope_rename(args, "macho")


def scope_rename(args, fmt):
    macho = fmt == "macho"
    reserved = MACHO_RESERVED if macho else COFF_RESERVED
    # Mach-O names keep their leading underscore: _sym -> _mp_rel_<Name>__sym.
    us = "_" if macho else ""

    mods = read_modules(args.modules)
    outputs = {n: o for n, o in read_modules(args.outputs)}
    others = [l for l in open(args.others).read().splitlines() if l.strip()]
    all_module_objs = {o for _, objs in mods for o in objs}
    others = [o for o in others if o not in all_module_objs]
    defined_outside = {s for s, t in nm(args.nm, others, "--defined-only", "-g") if t not in "Uu"}
    undef_outside = {s for s, t in nm(args.nm, others, "-u")}
    os.makedirs(args.outdir, exist_ok=True)

    info = {}  # name -> (per-object (defined, undefined), module defined, module-unresolved undefined)
    for name, objs in mods:
        if len(outputs.get(name, [])) != len(objs):
            sys.exit(f"scope_module: {name}: {len(objs)} objects but {len(outputs.get(name, []))} outputs "
                     "(an unexpected source type in the module?)")
        per = []
        for o in objs:
            per.append(({s for s, t in nm(args.nm, [o], "--defined-only", "-g") if t not in "Uu"},
                        {s for s, t in nm(args.nm, [o], "-u")}))
        defined = set().union(*(d for d, _ in per)) if per else set()
        undef = set().union(*(u for _, u in per)) - defined if per else set()
        info[name] = (per, defined, undef)

    for name, objs in mods:
        per, defined, _ = info[name]
        eps = entry_points(args.nm, objs)
        needed = set(undef_outside)
        for other, (_, _, undef) in info.items():
            if other != name:
                needed |= undef
        entry_names = {s for s in defined if any(rx.match(s) for rx in ENTRY.values())}
        rename = {s: (f"mp_rel_{name}__{s}" if not macho else
                      f"_mp_rel_{name}__{s[1:]}" if s.startswith("_") else f"mp_rel_{name}__{s}")
                  for s in defined
                  if s not in entry_names and s not in reserved
                  and not (s in needed and s not in defined_outside)}
        for kind, sym in eps.items():
            rename[sym] = f"{us}mp_rel_{name}_{kind}"
        for (obj, out, (d, u)) in zip(objs, outputs[name], per):
            os.makedirs(os.path.dirname(out), exist_ok=True)
            mapfile = out + ".redefine"
            open(mapfile, "w").write("".join(f"{s} {rename[s]}\n" for s in sorted((d | u) & rename.keys())))
            tmp = out + ".tmp"
            subprocess.run([args.objcopy, f"--redefine-syms={mapfile}", obj, tmp], check=True)
            os.replace(tmp, out)
            os.remove(mapfile)
            if macho:
                continue
            # Linker directives name symbols textually (/include:, /alternatename:); a renamed one
            # would silently dangle.
            drectve = out + ".drectve"
            if subprocess.run([args.objcopy, f"--dump-section=.drectve={drectve}", out, os.devnull],
                              capture_output=True).returncode == 0 and os.path.exists(drectve):
                text = open(drectve, errors="replace").read()
                os.remove(drectve)
                for s in d | u:
                    if s in rename and re.search(r"(include|alternatename|export):\"?" + re.escape(s) + r"[\"=\s,]", text):
                        print(f"scope_module: warning: {obj}: .drectve names renamed symbol {s}", file=sys.stderr)


SCOPERS = {"elf": scope, "coff": scope_coff, "macho": scope_macho}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", choices=["registry", "scope"])
    ap.add_argument("--modules", required=True)
    ap.add_argument("--out")
    ap.add_argument("--others")
    ap.add_argument("--outdir")
    ap.add_argument("--ld", default="ld.bfd")
    ap.add_argument("--objcopy", default="objcopy")
    ap.add_argument("--nm", default="nm")
    ap.add_argument("--format", choices=sorted(SCOPERS), default="elf")
    ap.add_argument("--outputs")
    args = ap.parse_args()
    (registry if args.mode == "registry" else SCOPERS[args.format])(args)


if __name__ == "__main__":
    sys.exit(main())
